const norm = (code) => String(code || '').toLowerCase().replace(/_/g, '-').trim();

export function registerLocale(code, labels) {
  LOCALES[norm(code)] = { ...(LOCALES[norm(code)] || {}), ...labels };
}

export function resolveLocaleCode(code) {
  const c = norm(code);
  if (c && LOCALES[c]) return c;
  const base = c.split('-')[0];
  return base && LOCALES[base] ? base : 'en';
}

export function getLabels(code, overrides = {}) {
  return { ...DEFAULT_LABELS, ...LOCALES[resolveLocaleCode(code)], ...overrides };
}
